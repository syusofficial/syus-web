/**
 * 2026 추석 인사 — 노출 기간 한 곳에서만 정한다.
 *
 * 인사 배너(ChuseokGreeting)와 등록 유도 카드(MuolRegisterPrompt)가 같은 값을 읽는다.
 * 두 카드가 한 화면에 겹치면 둘 다 잡음이 되므로, 이 기간에는 인사가 우선이고
 * 등록 유도는 쉰다. 한쪽에만 날짜를 적어두면 다음 명절에 반드시 어긋난다.
 *
 * 기간이 지나면 코드를 지우지 않아도 저절로 사라진다 — 운영자가 내려야 할 일을 만들지 않는다.
 */

/** 연휴 하루 전부터 띄운다 — 안내는 연휴가 시작되기 전에 닿아야 쓸모가 있다. */
const START = new Date(2026, 8, 23, 0, 0, 0); // 2026-09-23 (수)
/** 연휴(9/24 목 ~ 9/26 토) 다음 날 밤까지. 이후 자동 소멸. */
const END = new Date(2026, 8, 27, 23, 59, 59); // 2026-09-27 (일)

/** 연휴 표기 — 배너와 캡션이 같은 문장을 쓰게 한다. */
export const CHUSEOK_HOLIDAY_LABEL = "9월 24일(목) ~ 9월 26일(토)";

/**
 * 지금이 인사 기간인가.
 * 반드시 클라이언트에서(useEffect 안에서) 부른다 — 서버와 브라우저의 시계가 달라
 * 렌더 결과가 갈리면 하이드레이션이 깨진다.
 */
export function isChuseokWindow(now: Date = new Date()): boolean {
  return now >= START && now <= END;
}
